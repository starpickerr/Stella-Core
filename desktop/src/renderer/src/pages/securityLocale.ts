export type SecurityCopy = typeof locales.zh | typeof locales.en
export const securityCopy = (language: string): SecurityCopy => locales[language === 'en' ? 'en' : 'zh']

const fromMap = (map: Record<string, string>, key: string): string => map[key] || key

export function securityRuleName(copy: SecurityCopy, key: string): string {
  return (copy.rules as Record<string, { name: string }>)[key]?.name || key
}

export function securitySecretName(copy: SecurityCopy, name: string, displayName?: string): string {
  if (name.startsWith('CUSTOM:')) return displayName?.trim() || copy.customProvider
  const known = commonCredentials.find(([key]) => key === name)
  return known ? `${name === 'QIANFAN_API_KEY' ? copy.qianfanName : known[1]} ${copy.secretKeyLabel}` : name
}

export function securityResource(copy: SecurityCopy, value: string): string {
  if (value.startsWith('credential:')) return `${copy.resources['Credential Store']} · ${value.slice(11)}`
  return fromMap(copy.resources, value)
}

export function securityReason(copy: SecurityCopy, row: SecurityRecord): string {
  const reason = row.reason || ''
  const rule = reason.match(/; (required )?rule ([a-z_]+)\./)
  if (reason.startsWith('Policy allowed')) return copy.reasonAllow
  if (reason.startsWith('Policy denied') && rule)
    return rule[1]
      ? copy.reasonRequired(securityRuleName(copy, rule[2]))
      : copy.reasonPolicy(securityRuleName(copy, rule[2]))
  if (reason.startsWith('Connection ') && reason.endsWith(' was revoked.')) return copy.reasonRevoked
  if (reason.startsWith('Connection ') && reason.includes(' does not grant scope ')) return copy.reasonScope
  if (reason.startsWith('Shell write target is outside')) return copy.reasonOutside
  if (reason.startsWith('Shell command could not be parsed')) return copy.reasonUnclearCommand
  if (reason.startsWith('Credential contents are unavailable')) return copy.reasonCredential
  if (reason.startsWith('Shell access to credential')) return copy.reasonShellCredential
  if (reason.startsWith('Privilege escalation')) return copy.reasonEscalation
  if (reason.startsWith('Tool is outside the current allowlist')) return copy.reasonAllowlist
  if (reason.startsWith('Account is outside the current scope')) return copy.reasonAccount
  if (reason.startsWith('Unknown or mismatched capability') || reason.startsWith('Unknown tool capability'))
    return copy.reasonUnknownTool
  if (reason.startsWith('Approved once') || reason.startsWith('User approved')) return copy.reasonApproved
  if (reason.startsWith('User rejected')) return copy.reasonRejected
  if (reason.startsWith('Confirmation required') || reason.startsWith('Policy requires confirmation'))
    return copy.reasonConfirm
  if (reason.includes('policy updated') || reason.includes('security difference updated'))
    return copy.reasonPolicyChanged
  if (reason.includes('Credential status changed') || reason.includes('credential status changed'))
    return copy.reasonSecretChanged
  if (reason.includes('Credential status read')) return copy.reasonSecretMasked
  return copy.reasonFallback
}

export function securityTrace(copy: SecurityCopy, trace: string[]): string[] {
  return trace.flatMap((step) => {
    const action = step.match(/^Action: (.+)$/)
    if (action) return [`${copy.traceAction}${copy.fieldSeparator}${fromMap(copy.operations, action[1])}`]
    const resource = step.match(/^Resource classification: ([a-z-]+) \((.+)\)$/)
    if (resource) return [`${copy.traceResource}${copy.fieldSeparator}${securityResource(copy, resource[2])}`]
    const risk = step.match(/^Risk evaluation: (L[0-4])$/)
    if (risk) return [`${copy.traceRisk}${copy.fieldSeparator}${fromMap(copy.risk, risk[1])}`]
    const policy = step.match(/^(?:Required policy|Policy): ([a-z_]+)=(allow|confirm|deny)$/)
    if (policy)
      return [
        `${copy.tracePolicy}${copy.fieldSeparator}${securityRuleName(copy, policy[1])} · ${fromMap(copy.decisions, policy[2])}`,
      ]
    const decision = step.match(/^Decision: (allow|confirm|deny)/)
    if (decision) return [`${copy.traceResult}${copy.fieldSeparator}${fromMap(copy.outcomes, decision[1])}`]
    return []
  })
}
